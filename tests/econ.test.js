'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = { globalThis: null }; context.globalThis = context; vm.createContext(context);
for (const file of ['optimizer-catalog.js', 'optimizer-combat-stats.js', 'econ-pools.js', 'econ-core-v2.js']) vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context);
const items = context.BB_ECON_CORE.buildEconomyItems(context.BB_OPTIMIZER_CATALOG, context.BB_OPTIMIZER_COMBAT_STATS, { starCount: 1, emptySlots: 1, winRate: 50 });
const byId = new Map(items.map((item) => [item.id, item]));
assert.equal(context.BB_ECON_POOLS.pools.fishingShallow.names.length, 15);
assert.equal(context.BB_ECON_POOLS.pools.fishingDeep.names.length, 29);
assert.equal(context.BB_ECON_POOLS.pools.fishingAbyssal.names.length, 38);
assert.equal(context.BB_ECON_POOLS.pools.miningSurface.names.length, 4);
assert.equal(byId.get('cast-net').pools[0].label, 'Fishing · Shallow');
assert.equal(byId.get('cast-net').pools[0].candidates.length, 15);
assert.equal(byId.get('gemforged-warpick').pools[0].label, 'Mining · Core');
assert.ok(byId.get('wildflower-symphony').pools.some((pool) => pool.label === 'Insect'));
assert.match(byId.get('cast-net').displayGold, /\+a$/);
assert.ok(Number.isFinite(byId.get('cast-net').pools[0].lowestAverageSale));
assert.equal(byId.get('gold-bar').displayGold, '5');
const html = fs.readFileSync(path.join(root, 'econ.html'), 'utf8');
for (const asset of ['styles.css', 'optimizer.css', 'econ.css', 'econ-pools.js', 'econ-core-v2.js', 'econ-app-v2.js']) assert.ok(html.includes(asset), `econ.html must load ${asset}`);
assert.equal(/<(script|link|img)[^>]+(?:src|href)="https?:/i.test(html), false);
console.log('econ tests passed');
